def safe_num(v, default=0):
    try:
        if v in (None, ""):
            return default
        return float(v)
    except (TypeError, ValueError):
        return default


def safe_year(v):
    """YEARBUILT / YEARUPGRAD must be a plain 4-digit year integer - NOT a date string."""
    n = safe_num(v, 0)
    return int(n) if n > 1752 else ""


