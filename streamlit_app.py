def _secret(name, default=""):
    """Value from Streamlit Secrets (Manage app -> Settings -> Secrets), or `default` if not set / no secrets file."""
    try:
        v = st.secrets.get(name, default)
    except Exception:                                # noqa: BLE001  (no secrets file at all)
        return default
    return str(v).strip() if v not in (None, "") else default


def _key_box(label, secret_name, help_text):
    """Password box that falls back to the saved Secrets value. Returns (key, from_secrets)."""
    saved = _secret(secret_name)
    typed = st.text_input(label, type="password", help=help_text,
                          placeholder="🔐 saved key in use - type only to override" if saved else "")
    return (typed or "").strip() or saved, bool(saved) and not (typed or "").strip()


