def _load_one(_name, _blob):
    _src = _zlib.decompress(_b64.b64decode(_blob)).decode("utf-8")
    _tag = _hl.md5(_src.encode("utf-8")).hexdigest()
    _mod = _sys.modules.get(_name)
    if _mod is not None and getattr(_mod, "__bundle_loaded__", None) == _tag:
        return                            # fully loaded by an earlier rerun
    _sys.modules.pop(_name, None)         # drop any half-loaded leftover from a failed attempt
    _mod = _types.ModuleType(_name)
    _mod.__file__ = f"<bundled {_name}.py>"
    _sys.modules[_name] = _mod            # register BEFORE exec (dataclasses / cross-imports)
